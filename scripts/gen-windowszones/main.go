// Command gen-windowszones writes the Windows-name to IANA-name table used by
// icalevent.Zone, from a copy of CLDR's windowsZones.xml.
//
//	go run ../../scripts/gen-windowszones -in testdata/windowsZones.xml \
//	    -out windowszones_gen.go -tag release-48
//
// Only territory "001" rows are read: that is CLDR's primary zone for each
// Windows name. The XML does not carry the CLDR version, so -tag names the
// release the file was taken from.
package main

import (
	"bytes"
	"encoding/xml"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"io"
	"os"
	"sort"
	"strings"
)

// cldrTag is the CLDR release the checked-in XML copy was taken from.
const cldrTag = "release-48"

const sourceURL = "https://raw.githubusercontent.com/unicode-org/cldr/%s/common/supplemental/windowsZones.xml"

type mapZone struct {
	Other     string `xml:"other,attr"`
	Territory string `xml:"territory,attr"`
	Type      string `xml:"type,attr"`
}

type supplementalData struct {
	Zones []mapZone `xml:"windowsZones>mapTimezones>mapZone"`
}

func main() {
	os.Exit(run(os.Args[1:], os.Stderr))
}

func run(args []string, stderr io.Writer) int {
	fs := flag.NewFlagSet("gen-windowszones", flag.ContinueOnError)
	fs.SetOutput(stderr)
	in := fs.String("in", "", "path of windowsZones.xml")
	out := fs.String("out", "", "path of the Go file to write")
	tag := fs.String("tag", "", "CLDR release tag the XML was taken from, e.g. release-48")
	if err := fs.Parse(args); err != nil {
		return 2
	}
	if *in == "" || *out == "" || *tag == "" {
		fmt.Fprintln(stderr, "gen-windowszones: -in, -out and -tag are required")
		return 2
	}
	src, err := os.ReadFile(*in)
	if err != nil {
		fmt.Fprintln(stderr, "gen-windowszones:", err)
		return 1
	}
	code, err := generate(src, *tag)
	if err != nil {
		fmt.Fprintln(stderr, "gen-windowszones:", err)
		return 1
	}
	if err := os.WriteFile(*out, code, 0o600); err != nil {
		fmt.Fprintln(stderr, "gen-windowszones:", err)
		return 1
	}
	return 0
}

// generate returns the formatted Go source for the territory 001 rows of src.
func generate(src []byte, tag string) ([]byte, error) {
	var doc supplementalData
	if err := xml.Unmarshal(src, &doc); err != nil {
		return nil, fmt.Errorf("parse windowsZones.xml: %w", err)
	}
	table := map[string]string{}
	for _, z := range doc.Zones {
		if z.Territory != "001" {
			continue
		}
		fields := strings.Fields(z.Type)
		if z.Other == "" || len(fields) == 0 {
			return nil, fmt.Errorf("territory 001 row %q has no name or type", z.Other)
		}
		if prev, dup := table[z.Other]; dup && prev != fields[0] {
			return nil, fmt.Errorf("territory 001 lists %q twice", z.Other)
		}
		table[z.Other] = fields[0]
	}
	if len(table) == 0 {
		return nil, errors.New("no territory 001 rows found")
	}
	keys := make([]string, 0, len(table))
	for k := range table {
		keys = append(keys, k)
	}
	sort.Strings(keys)

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by scripts/gen-windowszones from CLDR %s; DO NOT EDIT.\n", tag)
	fmt.Fprintf(&b, "// Source: "+sourceURL+" (territory \"001\" rows).\n\n", tag)
	b.WriteString("package icalevent\n\n")
	b.WriteString("// windowsZones maps a Windows time-zone name to the IANA zone CLDR gives it.\n")
	b.WriteString("var windowsZones = map[string]string{\n")
	for _, k := range keys {
		fmt.Fprintf(&b, "\t%q: %q,\n", k, table[k])
	}
	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format output: %w", err)
	}
	return out, nil
}
