func TestGenerate(t *testing.T) {
	const fixture = `<supplementalData><windowsZones><mapTimezones>
<mapZone other="B Standard Time" territory="001" type="Europe/Berlin Europe/Vienna"/>
<mapZone other="A Standard Time" territory="001" type="Asia/Tokyo"/>
<mapZone other="A Standard Time" territory="JP" type="Asia/Other"/>
</mapTimezones></windowsZones></supplementalData>`
	got, err := generate([]byte(fixture), "release-test")
	if err != nil {
		t.Fatal(err)
	}
	s := string(got)
	if !strings.HasPrefix(s, "// Code generated by scripts/gen-windowszones from CLDR release-test; DO NOT EDIT.") {
		t.Errorf("header: %q", s[:80])
	}
	if !strings.Contains(s, "release-test/common/supplemental/windowsZones.xml") {
		t.Error("header does not name the source URL")
	}
	a, b := strings.Index(s, `"A Standard Time": "Asia/Tokyo"`), strings.Index(s, `"B Standard Time": "Europe/Berlin"`)
	if a < 0 || b < 0 || a > b {
		t.Errorf("rows missing or unsorted:\n%s", s)
	}
	if strings.Contains(s, "Asia/Other") || strings.Contains(s, "Vienna") {
		t.Errorf("non-001 row or second zone leaked:\n%s", s)
	}
}

func TestGenerateRejects(t *testing.T) {
	for name, src := range map[string]string{
		"empty":   `<supplementalData/>`,
		"no 001":  `<supplementalData><windowsZones><mapTimezones><mapZone other="X" territory="US" type="A/B"/></mapTimezones></windowsZones></supplementalData>`,
		"no type": `<supplementalData><windowsZones><mapTimezones><mapZone other="X" territory="001" type=""/></mapTimezones></windowsZones></supplementalData>`,
		"bad xml": `<supplementalData`,
	} {
		if _, err := generate([]byte(src), "t"); err == nil {
			t.Errorf("%s: want error", name)
		}
	}
}

// TestCommittedTableIsCurrent regenerates the table from the checked-in XML so
// the committed Go file cannot drift from it.
func TestCommittedTableIsCurrent(t *testing.T) {
	src, err := os.ReadFile("../../internal/icalevent/testdata/windowsZones.xml")
	if err != nil {
		t.Fatal(err)
	}
	want, err := generate(src, cldrTag)
	if err != nil {
		t.Fatal(err)
	}
	have, err := os.ReadFile("../../internal/icalevent/windowszones_gen.go")
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(have, want) {
		t.Error("internal/icalevent/windowszones_gen.go is stale: run go generate ./internal/icalevent")
	}
}
