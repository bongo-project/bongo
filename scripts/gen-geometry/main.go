// Command gen-geometry writes the finite CSS utility classes used for
// CSP-safe client-side positioning.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
)

const defaultOutput = "internal/web/static/css/generated_geometry.css"

func main() {
	output := flag.String("out", defaultOutput, "generated CSS output path")
	flag.Parse()

	// #nosec G306 -- generated CSS is a public embedded static asset.
	if err := os.WriteFile(*output, generate(), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "write generated geometry: %v\n", err)
		os.Exit(1)
	}
}

func generate() []byte {
	var css bytes.Buffer
	css.WriteString("/* Code generated by go run ./scripts/gen-geometry; DO NOT EDIT. */\n")
	css.WriteString("/* CSP-safe positioning classes used by mail gestures, menus and calendars. */\n\n")

	for step := -200; step <= 200; step++ {
		fmt.Fprintf(&css, ".swipe-x-%d { transform: translateX(%dpx); }\n", step, step*4)
	}
	css.WriteByte('\n')

	writePixels := func(prefix, property string) {
		for step := 0; step <= 255; step++ {
			fmt.Fprintf(&css, ".%s-%d { %s: %dpx; }\n", prefix, step, property, step*8)
		}
		css.WriteByte('\n')
	}
	writePixels("ctx-left", "left")
	writePixels("ctx-top", "top")

	for minute := 0; minute < 24*60; minute++ {
		fmt.Fprintf(&css, ".cal-top-%d { top: %.6f%%; }\n", minute, float64(minute)/14.4)
	}
	css.WriteByte('\n')
	for minutes := 30; minutes <= 24*60; minutes++ {
		fmt.Fprintf(&css, ".cal-height-%d { height: %.6f%%; }\n", minutes, float64(minutes)/14.4)
	}

	return css.Bytes()
}
